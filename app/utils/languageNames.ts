/**
 * Get translated language name for a given code and locale.
 * Falls back to the code itself if not found.
 */
export function getLanguageName(code: string, locale: Locale): string {
  const entry = languageNames[code]
  if (!entry) return code
  return entry[locale] || code
}

/**
 * Get all language names for search indexing (both locales combined).
 */
export function getLanguageSearchNames(code: string): string[] {
  const entry = languageNames[code]
  if (!entry) return [code]
  return [entry.ua, entry.en]
}
